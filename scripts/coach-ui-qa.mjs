import { spawn, execFileSync } from 'node:child_process';
import { resolve, delimiter } from 'node:path';
import { existsSync, readFileSync } from 'node:fs';
import { requireIsolatedBrowser } from './browser-runtime.mjs';
requireIsolatedBrowser();
const expected=readFileSync('.nvmrc','utf8').trim().replace(/^v/,'');
const pin=resolve(`.agents/runtime/toolchain/node-v${expected}-darwin-${process.arch}/bin`);
if(existsSync(pin))process.env.PATH=pin+delimiter+'/Users/user/.npm-global/bin'+delimiter+process.env.PATH;
if(execFileSync('node',['--version'],{encoding:'utf8'}).trim()!=='v'+expected)throw Error('node_version_mismatch');
const run=(bin,args,env=process.env)=>new Promise((ok,no)=>{const p=spawn(bin,args,{cwd:resolve('.'),env,stdio:'inherit'});p.once('error',no);p.once('exit',code=>code===0?ok():no(Error('coach_ui_qa_failed:'+code)));});
